import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const scriptDir = path.dirname(scriptPath);
const appRoot = path.resolve(scriptDir, '..');
const require = createRequire(path.join(appRoot, 'package.json'));
const { minify } = require('terser');

export const bookmarkletInputPath = path.join(
  appRoot,
  'public/youtube-transcript.js'
);
export const bookmarkletOutputPath = path.join(appRoot, 'src/bookmarklet.ts');

function compactCssSegment(segment) {
  return segment
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s+/g, ' ')
    .replace(/\s*([{}:;,>])\s*/g, '$1')
    .trim();
}

function compactTaggedTemplateBody(templateBody) {
  let output = '';
  let cursor = 0;

  while (cursor < templateBody.length) {
    const expressionStart = templateBody.indexOf('${', cursor);

    if (expressionStart === -1) {
      output += compactCssSegment(templateBody.slice(cursor));
      break;
    }

    output += compactCssSegment(templateBody.slice(cursor, expressionStart));

    let depth = 1;
    let expressionEnd = expressionStart + 2;

    while (expressionEnd < templateBody.length && depth > 0) {
      const char = templateBody[expressionEnd];
      if (char === '{') {
        depth += 1;
      } else if (char === '}') {
        depth -= 1;
      }
      expressionEnd += 1;
    }

    output += templateBody.slice(expressionStart, expressionEnd);
    cursor = expressionEnd;
  }

  return output;
}

function compactStyleTemplates(source) {
  const marker = 'style.textContent = `';
  let output = '';
  let searchStart = 0;

  while (searchStart < source.length) {
    const markerIndex = source.indexOf(marker, searchStart);

    if (markerIndex === -1) {
      output += source.slice(searchStart);
      break;
    }

    output += source.slice(searchStart, markerIndex + marker.length);

    let cursor = markerIndex + marker.length;
    let templateBody = '';

    while (cursor < source.length) {
      const char = source[cursor];

      if (char === '\\') {
        templateBody += source.slice(cursor, cursor + 2);
        cursor += 2;
        continue;
      }

      if (char === '`') {
        break;
      }

      templateBody += char;
      cursor += 1;
    }

    output += compactTaggedTemplateBody(templateBody);
    output += '`';
    searchStart = cursor + 1;
  }

  return output;
}

export async function buildBookmarklet() {
  const source = compactStyleTemplates(
    fs.readFileSync(bookmarkletInputPath, 'utf8').trim()
  );
  const result = await minify(source, {
    compress: {
      defaults: true,
      passes: 2,
    },
    mangle: false,
    ecma: 2020,
    format: {
      beautify: false,
      comments: false,
      semicolons: true,
    },
  });

  if (!result.code) {
    throw new Error('Failed to generate bookmarklet code.');
  }

  const bookmarklet = `javascript:${result.code}`;
  const blockedTokens = [
    "createElement('script')",
    'createElement("script")',
    '.src=',
    'youtube-transcript.js',
  ];

  if (!bookmarklet.startsWith('javascript:')) {
    throw new Error('Generated bookmarklet is missing the javascript: prefix.');
  }

  for (const token of blockedTokens) {
    if (bookmarklet.includes(token)) {
      throw new Error(`Generated bookmarklet still contains blocked token: ${token}`);
    }
  }

  fs.mkdirSync(path.dirname(bookmarkletOutputPath), { recursive: true });
  fs.writeFileSync(
    bookmarkletOutputPath,
    [
      '// Generated by app/scripts/build-bookmarklet.mjs. Do not edit by hand.',
      `export const bookmarklet = ${JSON.stringify(bookmarklet)};`,
      '',
    ].join('\n')
  );

  return { bookmarklet, outputPath: bookmarkletOutputPath };
}

const isCliEntry =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(scriptPath);

if (isCliEntry) {
  buildBookmarklet()
    .then(({ outputPath }) => {
      console.log(`Wrote ${outputPath}`);
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}
